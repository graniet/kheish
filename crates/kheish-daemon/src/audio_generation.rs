impl AudioGenerationService {
    /// Builds one audio-generation service from provider-neutral backends.
    pub(crate) fn new(
        backends: BTreeMap<String, Arc<dyn AudioGenerationBackend>>,
        default_route_id: String,
        assets: Arc<FileAssetStore>,
    ) -> Result<Self> {
        if !backends.contains_key(&default_route_id) {
            bail!(
                "audio-generation default route '{}' is not configured",
                default_route_id
            );
        }
        Ok(Self {
            assets,
            backends,
            default_route_id,
        })
    }

    /// Generates one or more daemon-owned audio assets.
    #[cfg(test)]
    pub(crate) async fn generate(
        &self,
        request: GenerateAudioToolRequest,
        preferred_route_id: Option<&str>,
        credential_scope: Option<&kheish_types::CredentialScope>,
    ) -> Result<GenerateAudioToolResponse> {
        self.generate_with_context(
            request,
            preferred_route_id,
            credential_scope,
            AudioToolExecutionContext::default(),
        )
        .await
    }

    /// Generates one or more daemon-owned audio assets with durable provenance context.
    pub(crate) async fn generate_with_context(
        &self,
        request: GenerateAudioToolRequest,
        preferred_route_id: Option<&str>,
        credential_scope: Option<&kheish_types::CredentialScope>,
        context: AudioToolExecutionContext,
    ) -> Result<GenerateAudioToolResponse> {
        validate_audio_generation_request(&request)?;
        let selected_route_id = select_audio_generation_route_id(
            &self.backends,
            &request.route,
            preferred_route_id,
            &self.default_route_id,
            credential_scope,
        )?;
        let backend = self.backends.get(selected_route_id).ok_or_else(|| {
            anyhow!("no audio-generation backend is configured for route {selected_route_id}")
        })?;
        let generated = backend
            .generate(&request, request.route.model.as_deref())
            .await?;
        self.persist_generated_audio(generated, selected_route_id, context, &request)
    }

    fn persist_generated_audio(
        &self,
        generated: GeneratedAudioBatch,
        route_id: &str,
        context: AudioToolExecutionContext,
        request: &GenerateAudioToolRequest,
    ) -> Result<GenerateAudioToolResponse> {
        validate_generated_audio_batch(&generated)?;
        let mut attachments = Vec::with_capacity(generated.assets.len());
        let output_count = generated.assets.len() as u32;
        let prompt_sha256 = audio_generation_prompt_sha256(request);
        for (index, asset) in generated.assets.iter().enumerate() {
            let media_type = normalize_generated_audio_media_type(&asset.media_type);
            let extension = preferred_extension_for_audio_media_type(&media_type)?;
            let mut record = self.assets.import_bytes_with_provenance(
                &format!(
                    "generated-audio-{}-{}.{}",
                    generated.model,
                    index + 1,
                    extension
                ),
                Some(&media_type),
                &asset.bytes,
                Some(AssetProvenanceRecord {
                    kind: "audio_generation".to_string(),
                    tool_name: "generate_audio".to_string(),
                    session_id: context.session_id.clone(),
                    run_id: context.run_id.clone(),
                    tool_call_id: context.tool_call_id.clone(),
                    route_id: Some(route_id.to_string()),
                    provider: generated.provider.clone(),
                    model: generated.model.clone(),
                    prompt_sha256: prompt_sha256.clone(),
                    source_assets: Vec::new(),
                    output_index: index as u32 + 1,
                    output_count,
                }),
            )?;
            if let Some(transcript) = generated.transcript.as_deref().map(str::trim)
                && !transcript.is_empty()
            {
                let text_asset = self.assets.import_bytes(
                    &format!("generated-audio-{}-{}.txt", generated.model, index + 1),
                    Some("text/plain"),
                    transcript.as_bytes(),
                )?;
                record = self.assets.attach_text_asset(&record.id, &text_asset)?;
            }
            attachments.push(record.attachment_ref());
        }
        Ok(GenerateAudioToolResponse {
            provider: generated.provider,
            model: generated.model,
            route_id: Some(route_id.to_string()),
            assets: attachments,
            transcript: generated.transcript,
        })
    }
}

pub(crate) fn audio_generation_backend_from_route(
    route_id: &str,
    route: &ModelRouteConfig,
    observer: Arc<dyn RuntimeObserver>,
) -> Result<Option<(String, Arc<dyn AudioGenerationBackend>)>> {
    match route {
        ModelRouteConfig::OpenAi(config) => Ok(Some((
            route_id.to_string(),
            Arc::new(OpenAiAudioGenerationBackend::from_config(
                config.clone(),
                observer,
            )),
        ))),
        ModelRouteConfig::OpenRouter(config) => Ok(Some((
            route_id.to_string(),
            Arc::new(OpenRouterAudioGenerationBackend::from_config(
                config.clone(),
                observer,
            )),
        ))),
        ModelRouteConfig::Anthropic(_) | ModelRouteConfig::Google(_) | ModelRouteConfig::XAi(_) => {
            Ok(None)
        }
    }
}

fn select_audio_generation_route_id<'a>(
    backends: &'a BTreeMap<String, Arc<dyn AudioGenerationBackend>>,
    route_override: &'a ImageToolRouteOverride,
    preferred_route_id: Option<&'a str>,
    default_route_id: &'a str,
    credential_scope: Option<&kheish_types::CredentialScope>,
) -> Result<&'a str> {
    if let Some(route_id) = route_override.provider.as_deref() {
        ensure_route_allowed(credential_scope, route_id)?;
        if backends.contains_key(route_id) {
            return Ok(route_id);
        }
        bail!("no audio-generation backend is configured for route {route_id}");
    }
    if let Some(route_id) = preferred_route_id
        .filter(|route_id| backends.contains_key(*route_id))
        .filter(|route_id| route_is_allowed(credential_scope, route_id))
    {
        return Ok(route_id);
    }
    if route_is_allowed(credential_scope, default_route_id) {
        return Ok(default_route_id);
    }
    if let Some(route_id) = backends
        .keys()
        .find(|route_id| route_is_allowed(credential_scope, route_id))
    {
        return Ok(route_id.as_str());
    }
    if credential_scope.is_some() {
        bail!("credential scope blocks all audio-generation routes");
    }
    Ok(default_route_id)
}

fn route_is_allowed(
    credential_scope: Option<&kheish_types::CredentialScope>,
    route_id: &str,
) -> bool {
    credential_scope.is_none_or(|scope| scope.is_empty() || scope.allows_route(route_id))
}

fn ensure_route_allowed(
    credential_scope: Option<&kheish_types::CredentialScope>,
    route_id: &str,
) -> Result<()> {
    anyhow::ensure!(
        route_is_allowed(credential_scope, route_id),
        "credential scope blocks route {route_id}"
    );
    Ok(())
}

fn validate_audio_generation_request(request: &GenerateAudioToolRequest) -> Result<()> {
    let input_chars = request.input.trim().chars().count();
    if input_chars == 0 {
        bail!("audio generation input must not be empty");
    }
    if input_chars > MAX_AUDIO_INPUT_CHARS {
        bail!(
            "audio generation input exceeds the {} character limit",
            MAX_AUDIO_INPUT_CHARS
        );
    }
    if let Some(instructions) = request.instructions.as_deref() {
        let instructions_chars = instructions.trim().chars().count();
        if instructions_chars > MAX_AUDIO_INSTRUCTIONS_CHARS {
            bail!(
                "audio generation instructions exceed the {} character limit",
                MAX_AUDIO_INSTRUCTIONS_CHARS
            );
        }
    }
    if let Some(voice) = request.voice.as_deref() {
        let voice = voice.trim();
        if voice.chars().count() > MAX_AUDIO_VOICE_CHARS {
            bail!(
                "audio generation voice exceeds the {} character limit",
                MAX_AUDIO_VOICE_CHARS
            );
        }
        if !voice.is_empty()
            && !voice.chars().all(|character| {
                character.is_ascii_alphanumeric() || matches!(character, '_' | '-')
            })
        {
            bail!("audio generation voice must contain only ASCII letters, digits, '_' or '-'");
        }
    }
    if let Some(format) = request.format.as_deref() {
        let format = format.trim().to_ascii_lowercase();
        if format.chars().count() > MAX_AUDIO_FORMAT_CHARS {
            bail!(
                "audio generation format exceeds the {} character limit",
                MAX_AUDIO_FORMAT_CHARS
            );
        }
        if !format.is_empty() && !audio_generation_format_supported(&format) {
            bail!("unsupported audio generation format `{format}`");
        }
    }
    if let Some(speed) = request.speed
        && (!speed.is_finite() || !(0.25..=4.0).contains(&speed))
    {
        bail!("audio generation speed must be between 0.25 and 4.0");
    }
    Ok(())
}

fn audio_generation_format_supported(format: &str) -> bool {
    matches!(
        format.trim().to_ascii_lowercase().as_str(),
        "mp3" | "wav" | "pcm" | "opus" | "aac" | "flac"
    )
}

fn validate_generated_audio_batch(generated: &GeneratedAudioBatch) -> Result<()> {
    if generated.assets.is_empty() {
        bail!("audio generation provider returned no assets");
    }
    if generated.assets.len() > MAX_GENERATED_AUDIO_ASSETS {
        bail!(
            "audio generation provider returned {} assets; at most {} is supported",
            generated.assets.len(),
            MAX_GENERATED_AUDIO_ASSETS
        );
    }
    for asset in &generated.assets {
        let media_type = normalize_generated_audio_media_type(&asset.media_type);
        preferred_extension_for_audio_media_type(&media_type)?;
        validate_generated_audio_payload(&media_type, &asset.bytes)?;
    }
    Ok(())
}

fn validate_generated_audio_payload(media_type: &str, bytes: &[u8]) -> Result<()> {
    if bytes.is_empty() {
        bail!("audio generation provider returned an empty payload");
    }
    if bytes.len() > MAX_ASSET_BYTES {
        bail!(
            "audio generation provider payload exceeds the {} byte limit",
            MAX_ASSET_BYTES
        );
    }
    match media_type {
        "audio/mp3" => validate_supported_audio_payload("audio/mpeg", bytes),
        "audio/x-wav" => validate_supported_audio_payload("audio/wav", bytes),
        "audio/x-aac" => validate_supported_audio_payload("audio/aac", bytes),
        "audio/x-flac" => validate_supported_audio_payload("audio/flac", bytes),
        "audio/x-m4a" => validate_supported_audio_payload("audio/m4a", bytes),
        "audio/mpeg" | "audio/mpga" | "audio/wav" | "audio/opus" | "audio/aac" | "audio/flac"
        | "audio/mp4" | "audio/m4a" | "audio/pcm" | "audio/l16" | "audio/l24" => {
            validate_supported_audio_payload(media_type, bytes)
        }
        other => bail!("unsupported generated audio media type {other}"),
    }
}

fn preferred_extension_for_audio_media_type(media_type: &str) -> Result<&'static str> {
    match media_type {
        "audio/mpeg" | "audio/mp3" => Ok("mp3"),
        "audio/wav" | "audio/x-wav" => Ok("wav"),
        "audio/pcm" | "audio/l16" | "audio/l24" => Ok("pcm"),
        "audio/opus" => Ok("opus"),
        "audio/aac" | "audio/x-aac" => Ok("aac"),
        "audio/flac" | "audio/x-flac" => Ok("flac"),
        "audio/mp4" => Ok("mp4"),
        "audio/m4a" | "audio/x-m4a" => Ok("m4a"),
        other => bail!("unsupported generated audio media type {other}"),
    }
}

fn normalize_generated_audio_media_type(media_type: &str) -> String {
    media_type
        .split(';')
        .next()
        .unwrap_or(media_type)
        .trim()
        .to_ascii_lowercase()
}

fn audio_generation_prompt_sha256(request: &GenerateAudioToolRequest) -> String {
    let mut hasher = Sha256::new();
    hash_labeled_text(&mut hasher, "input", request.input.trim());
    hash_labeled_text(
        &mut hasher,
        "instructions",
        request.instructions.as_deref().unwrap_or("").trim(),
    );
    hex::encode(hasher.finalize())
}

fn hash_labeled_text(hasher: &mut Sha256, label: &str, value: &str) {
    hasher.update(label.as_bytes());
    hasher.update([0]);
    hasher.update(value.len().to_be_bytes());
    hasher.update(value.as_bytes());
    hasher.update([0xff]);
}

