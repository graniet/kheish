const MAX_AUDIO_INPUT_CHARS: usize = 4_096;
const MAX_AUDIO_INSTRUCTIONS_CHARS: usize = 4_000;
const MAX_AUDIO_VOICE_CHARS: usize = 96;
const MAX_AUDIO_FORMAT_CHARS: usize = 16;
const MAX_GENERATED_AUDIO_ASSETS: usize = 1;

/// One provider-specific generated audio payload.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct GeneratedAudioPayload {
    /// The normalized MIME type returned by the provider.
    pub media_type: String,
    /// The encoded audio bytes persisted by the daemon asset store.
    pub bytes: Vec<u8>,
}

/// One provider-specific audio-generation result batch.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub(crate) struct GeneratedAudioBatch {
    /// The provider that generated the audio.
    pub provider: String,
    /// The concrete provider model that generated the audio.
    pub model: String,
    /// The generated audio payloads.
    pub assets: Vec<GeneratedAudioPayload>,
    /// Optional transcript associated with the generated audio.
    pub transcript: Option<String>,
}

/// Run/session context used to stamp daemon-generated audio assets with provenance.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub(crate) struct AudioToolExecutionContext {
    /// The session that requested the audio operation.
    pub session_id: Option<String>,
    /// The run that requested the audio operation.
    pub run_id: Option<String>,
    /// The tool-call id that requested the audio operation.
    pub tool_call_id: Option<String>,
}

/// Provider-neutral audio-generation backend contract.
#[async_trait]
pub(crate) trait AudioGenerationBackend: Send + Sync {
    /// Returns the stable provider name exposed by this backend.
    fn provider(&self) -> &str;

    /// Generates one or more audio assets for the provided request.
    async fn generate(
        &self,
        request: &GenerateAudioToolRequest,
        model_override: Option<&str>,
    ) -> Result<GeneratedAudioBatch>;
}

/// One daemon-owned audio-generation service that persists generated bytes as assets.
pub(crate) struct AudioGenerationService {
    assets: Arc<FileAssetStore>,
    backends: BTreeMap<String, Arc<dyn AudioGenerationBackend>>,
    default_route_id: String,
}

